export function presetTheme(key: string): Theme {
  const p: Partial<Preset> = { ...(PRESETS[key] ?? PRESETS.mint) };
  delete p.name;
  return { ...(p as Omit<Preset, "name">), preset: key, bgImageUrl: "" };
}

export function fontVar(key: FontKey) {
  return `var(--f-${key})`;
}
